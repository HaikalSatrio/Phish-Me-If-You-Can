func CanonicalRole(value string) string {
	return canonicalEnglishRole(value)
}

func canonicalEnglishRole(value string) string {
	value = strings.Join(strings.Fields(value), " ")
	if value == "" {
		return ""
	}
	if english, ok := roleEnglishExact[strings.ToLower(value)]; ok {
		return english
	}
	for _, phrase := range roleEnglishPhrases {
		value = phrase.re.ReplaceAllString(value, phrase.english)
	}
	tokens := strings.Fields(value)
	translated := make([]string, 0, len(tokens))
	for _, token := range tokens {
		key := strings.ToLower(strings.Trim(token, ".,;:!?()[]{}"))
		english, ok := roleEnglishWords[key]
		if !ok {
			translated = append(translated, token)
			continue
		}
		if english != "" {
			translated = append(translated, english)
		}
	}
	return strings.Join(strings.Fields(strings.Join(translated, " ")), " ")
}
